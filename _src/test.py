    pg.keyboard.press('ArrowRight');print('lb2',pg.inner_text('.lb p'));pg.keyboard.press('Escape')
    pg.goto(B+'?team=1');print('cd',pg.inner_text('[data-countdown]'))
    print('ERR',errs)
    b.close()
